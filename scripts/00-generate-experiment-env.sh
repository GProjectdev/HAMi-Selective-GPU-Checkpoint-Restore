#!/usr/bin/env bash
set -Eeuo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTPUT_FILE="${REPO_ROOT}/config/experiment.env"
FORCE=false
DRY_RUN=false

log() { printf '[%s] %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$*" >&2; }
die() { log "ERROR: $*"; exit 1; }

usage() {
  cat <<'EOF'
Usage: scripts/00-generate-experiment-env.sh [--force] [--dry-run] [--output PATH]

Generate config/experiment.env with best-effort auto-detected values.

Options:
  --force       overwrite an existing config/experiment.env
  --dry-run     print the generated env file without writing it
  --output PATH write to a custom path
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --force) FORCE=true ;;
    --dry-run) DRY_RUN=true ;;
    --output) shift; OUTPUT_FILE="${1:?missing output path}" ;;
    --help|-h) usage; exit 0 ;;
    *) die "Unknown argument: $1" ;;
  esac
  shift
done

if [[ -f "${OUTPUT_FILE}" && "${FORCE}" != "true" && "${DRY_RUN}" != "true" ]]; then
  die "${OUTPUT_FILE} already exists. Use --force to overwrite."
fi

command_exists() {
  command -v "$1" >/dev/null 2>&1
}

BASE_CR_REPO="../K8s-Native-Fast-GPU-Checkpoint-Restore-System"
RESTORE_CR_REPO="../K8s-Native-GPU-Restore-CRI-O"

detect_gpu_nodes() {
  if ! command_exists kubectl; then
    return 0
  fi
  kubectl get nodes -o jsonpath='{range .items[*]}{.metadata.name}{"\t"}{.status.allocatable.nvidia\.com/gpu}{"\n"}{end}' 2>/dev/null |
    awk '$2 != "" && $2 != "0" {print $1}'
}

SOURCE_NODE=""
TARGET_NODE=""
mapfile -t GPU_NODES < <(detect_gpu_nodes)
if [[ ${#GPU_NODES[@]} -gt 0 ]]; then
  SOURCE_NODE="${GPU_NODES[0]}"
  TARGET_NODE="${SOURCE_NODE}"
fi

find_repo_value() {
  local regex="$1"
  local base="${REPO_ROOT}/${BASE_CR_REPO}"
  [[ -d "${base}" ]] || return 0
  grep -RhoE --exclude-dir=.git --exclude-dir=vendor "${regex}" "${base}" 2>/dev/null | head -n 1 || true
}

GCR_LIBRARY_PATH="/var/lib/gpu-cr/lib/libgcr-interceptor.so"
CUDA_CHECKPOINT_BIN="$(find_repo_value "/[^[:space:]\"']*cuda-checkpoint" || true)"
CRIUGPU_PATH="$(find_repo_value "/[^[:space:]\"']*criugpu[^[:space:]\"']*" || true)"
SHARED_CHECKPOINT_ROOT="$(find_repo_value "/[^[:space:]\"']*(nfs|checkpoint|checkpoints)[^[:space:]\"']*" || true)"

CUDA_CHECKPOINT_BIN="${CUDA_CHECKPOINT_BIN:-/usr/local/bin/cuda-checkpoint}"
CRIUGPU_PATH="${CRIUGPU_PATH:-/usr/local/bin/criugpu}"
SHARED_CHECKPOINT_ROOT="${SHARED_CHECKPOINT_ROOT:-/mnt/nfs/gpu-checkpoints/hami-selective-cr}"

IMAGE_REGISTRY="${IMAGE_REGISTRY:-}"
TARGET_IMAGE="${TARGET_IMAGE:-}"
CO_RUNNER_IMAGE="${CO_RUNNER_IMAGE:-}"
WORKLOAD_BASE_IMAGE="${WORKLOAD_BASE_IMAGE:-nvidia/cuda:12.4.1-devel-ubuntu22.04}"

tmp_file="$(mktemp)"
cat > "${tmp_file}" <<EOF
# Auto-generated by scripts/00-generate-experiment-env.sh
# Generated at: $(date -u '+%Y-%m-%dT%H:%M:%SZ')
#
# Review this file once before running scripts with --yes.

EXPERIMENT_NAMESPACE=hami-selective-cr

BASE_CR_REPO=${BASE_CR_REPO}
RESTORE_CR_REPO=${RESTORE_CR_REPO}

# Auto-detected from kubectl if available. This experiment targets the same
# Worker Node by default, so TARGET_NODE is intentionally set to SOURCE_NODE.
# Empty means later scripts will try to detect a GPU node again.
SOURCE_NODE=${SOURCE_NODE}
TARGET_NODE=${TARGET_NODE}

GPU_RESOURCE_NAME=nvidia.com/gpu
HAMI_MEMORY_RESOURCE=nvidia.com/gpumem
HAMI_CORE_RESOURCE=nvidia.com/gpucores

POD_A_MEMORY_MB=8192
POD_A_CORE_PERCENT=20
POD_B_MEMORY_MB=8192
POD_B_CORE_PERCENT=20

LOCAL_CHECKPOINT_ROOT=/var/lib/gpu-cr/checkpoints/hami-selective-cr
SHARED_CHECKPOINT_ROOT=${SHARED_CHECKPOINT_ROOT}

GPU_CR_NAMESPACE=gpu-cr-system
GPU_CR_LIB_HOST_PATH=/var/lib/gpu-cr/lib
GCR_CONTROL_DIR=/var/lib/gpu-cr/run
GCR_DATA_DIR=/var/lib/gcr-data
CHECKPOINT_STORAGE_TYPE=hostPath
CHECKPOINT_STORAGE_PATH=/var/lib/gcr-checkpoint
RESTORE_BLOB_MODE=copy
RESTORE_TIMEOUT_SECONDS=300
REQUIRE_GCR_SELECTIVE_DATA=true
RESTORE_HAMI_VGPU_LOCK_SOURCE=/tmp/vgpulock
RESTORE_HAMI_LD_PRELOAD_SOURCE=/usr/local/vgpu/ld.so.preload
# Empty means scripts/09-run-pod-recreation-test.sh derives:
# /usr/local/vgpu/containers/<checkpoint-source-pod-uid>_selective-target
RESTORE_HAMI_VGPU_DIR_SOURCE=
RESTORE_HAMI_LIBVGPU_SOURCE=/usr/local/vgpu/libvgpu.so.v2.9.0

GCR_LIBRARY_PATH=${GCR_LIBRARY_PATH}
CUDA_CHECKPOINT_BIN=${CUDA_CHECKPOINT_BIN}
CRIU_BIN=criu
CRIUGPU_PATH=${CRIUGPU_PATH}

CONTAINER_RUNTIME=crio

RESULT_ROOT=./results
BACKUP_ROOT=./backups
STATE_ROOT=./.state

# Default path: no custom image build/push required. Pod A/B use this public
# CUDA devel image and compile the repo-provided CUDA source from ConfigMaps.
WORKLOAD_BASE_IMAGE=${WORKLOAD_BASE_IMAGE}

# Optional legacy image path. These are only needed if you choose to run
# scripts/04-build-test-images.sh and push custom images.
IMAGE_REGISTRY=${IMAGE_REGISTRY}
TARGET_IMAGE=${TARGET_IMAGE}
CO_RUNNER_IMAGE=${CO_RUNNER_IMAGE}

HAMI_VERSION=
HAMI_HELM_REPOSITORY=https://project-hami.github.io/HAMi/
HAMI_HELM_CHART=hami-charts/hami
EOF

if [[ "${DRY_RUN}" == "true" ]]; then
  cat "${tmp_file}"
  rm -f "${tmp_file}"
  exit 0
fi

mkdir -p "$(dirname "${OUTPUT_FILE}")"
mv "${tmp_file}" "${OUTPUT_FILE}"
log "Generated ${OUTPUT_FILE}"
if [[ -z "${SOURCE_NODE}" ]]; then
  log "SOURCE_NODE was not detected. Install kubectl/configure kube-context or fill it manually."
fi
if [[ ! -d "${REPO_ROOT}/${BASE_CR_REPO}" ]]; then
  log "Base C/R repository was not found at ${BASE_CR_REPO}; path-sensitive values used defaults."
fi
